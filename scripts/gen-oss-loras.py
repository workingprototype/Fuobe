#!/usr/bin/env python3
"""
Generate src/lib/catalog/oss-loras.generated.ts: Higgsfield preset name → Wan LoRAs for the
open-source (ComfyUI, Wan 2.2 14B I2V) version of camera motions and effects.
Source: docs/research/comfyui-oss.json "loras" (higgsfieldEquivalent column).

Wan 2.2 LoRAs come as high/low-noise pairs and are injected on the matching expert.
Wan 2.1 I2V LoRAs are applied to both Wan 2.2 experts (architecture-compatible; quality
should be validated per LoRA on a GPU — see docs/STATUS.md).
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "docs/research/comfyui-oss.json").read_text())


def slug(s):
    return re.sub(r"^-|-$", "", re.sub(r"[^a-z0-9]+", "-", s.lower()))


out = {}
for l in data["loras"]:
    base = l.get("baseModel", "")
    if l["type"] not in ("camera", "vfx") or not (base.startswith("wan2.1-i2v") or base.startswith("wan2.2-i2v")):
        continue
    eq = l.get("higgsfieldEquivalent") or ""
    names = [re.sub(r"\(.*?\)", "", n).strip() for n in re.split(r"/|,", eq)]
    names = [n for n in names if n and n != "-"]
    # Also index by the LoRA's own short name ("Remade-AI Squish" → "squish").
    own = re.sub(r"^(Remade-AI|ostris|wolfer45|joyfox|lovis93|artificialguybr)\s+", "", l["name"])
    own = re.sub(r"\(.*?\)|Wan2\.[12]\s*I2V|Wan2\.[12]|LoRA", "", own).strip()
    names.append(own)
    noise = "high" if "high noise" in l["name"].lower() else "low" if "low noise" in l["name"].lower() else "both"
    trigger = (l.get("trigger") or "").split("(")[0].strip().strip('"')
    if trigger.lower().startswith(("none", "see card")):
        trigger = ""
    ref = {
        "file": l.get("file") or l["url"].rsplit("/", 1)[-1],
        "url": l["url"],
        "strength": 1.0,
        "target": noise,
        **({"trigger": trigger} if trigger else {}),
        "base": base,
    }
    for n in names:
        key = slug(n)
        if not key:
            continue
        cur = out.setdefault(key, [])
        # Prefer native Wan 2.2 LoRAs over 2.1 ones for the same preset.
        if base.startswith("wan2.2") and cur and all(c["base"].startswith("wan2.1") for c in cur):
            cur.clear()
        if cur and base.startswith("wan2.1") and any(c["base"].startswith("wan2.2") for c in cur):
            continue
        if any(c["file"] == ref["file"] for c in cur):
            continue
        if base.startswith("wan2.1") and cur:
            continue  # one 2.1 LoRA per preset is enough
        cur.append(ref)

ts = (
    "// Generated by scripts/gen-oss-loras.py from docs/research/comfyui-oss.json — do not edit by hand.\n"
    'import type { LoraRef } from "./types";\n\n'
    "export type OssLora = LoraRef & { target: \"high\" | \"low\" | \"both\"; base: string };\n\n"
    "/** Keyed by slugified preset name (e.g. \"crash-zoom-in\"). */\n"
    f"export const OSS_LORAS: Record<string, OssLora[]> = {json.dumps(out, indent=2)};\n"
)
(ROOT / "src/lib/catalog/oss-loras.generated.ts").write_text(ts)
print(f"wrote {len(out)} preset → LoRA mappings")
