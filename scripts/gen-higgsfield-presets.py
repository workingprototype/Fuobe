#!/usr/bin/env python3
"""
Generate src/lib/catalog/higgsfield-presets.generated.ts from docs/research/higgsfield-image-studios.json.

Outputs (all static, used when there is no Higgsfield key or the live list fails):
  SOUL_PRESETS      — the 106 Soul (v1) presets and the 33 Soul 2.0 presets / curated moodboards:
                      id (the API's style_id), name, categories, description, whether the description
                      is ours (inferred) and, for Soul 2.0, whether it's one of the curated moodboards.
  SOUL_CATEGORIES   — the picker's category tabs per model, in Higgsfield's order.
  PHOTODUMP_PACKS   — Soul 2.0 Photodump packs and Instadump packs: name, photo count, description.
  FASHION_TEMPLATES — Fashion Factory templates: name, preview shot count, description.

No preview URLs are copied: Fuobe draws its own previews, so nothing is hot-linked from Higgsfield's CDN.

Run:  python3 scripts/gen-higgsfield-presets.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESEARCH = json.loads((ROOT / "docs/research/higgsfield-image-studios.json").read_text())
OUT = ROOT / "src/lib/catalog/higgsfield-presets.generated.ts"

V1_TABS = ["New", "TikTok Core", "Instagram Aesthetics", "Camera Presets", "Beauty", "Mood", "Surreal", "Graphic Art"]
V2_TABS = ["Mood", "Styles", "Camera"]


def warn(msg):
    print(f"warning: {msg}")


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def clean(s):
    return re.sub(r"\s+", " ", s or "").strip()


presets = []
for p in RESEARCH["soulPresets"]:
    model = p["model"]
    if model not in ("soul-v1", "soul-v2"):
        warn(f"unknown preset model {model}")
        continue
    cats = list(p.get("categories") or [])
    if model == "soul-v2" and p.get("category") and p["category"] != "All presets":
        cats = [p["category"]]
    tabs = V1_TABS if model == "soul-v1" else V2_TABS
    for c in cats:
        if c not in tabs:
            warn(f"{p['name']}: category {c} not in the {model} tabs")
    entry = {
        "id": p["id"],
        "name": clean(p["name"]),
        "model": model,
        "categories": cats,
        "description": clean(p["description"]),
        "inferred": p.get("descriptionSource") == "inferred",
    }
    if model == "soul-v2":
        entry["curated"] = bool(p.get("curatedMoodboard"))
    presets.append(entry)

ids = [p["id"] for p in presets]
if len(ids) != len(set(ids)):
    warn("duplicate preset ids")
counts = RESEARCH["counts"]
v1 = [p for p in presets if p["model"] == "soul-v1"]
v2 = [p for p in presets if p["model"] == "soul-v2"]
if len(v1) != counts["soulV1Presets"] or len(v2) != counts["soulV2Presets"]:
    warn(f"preset counts {len(v1)}/{len(v2)} differ from research counts {counts['soulV1Presets']}/{counts['soulV2Presets']}")

packs = []
for t in RESEARCH["photodump"]["templates"]:
    version = t.get("version", "")
    if version.startswith("legacy"):
        continue  # the fixed 26-shot Soul v1 set; superseded by the packs below
    product = "instadump" if version.startswith("Instadump") else "photodump"
    packs.append({
        "id": slug(t["name"]),
        "higgsfieldId": t.get("id"),
        "name": t["name"],
        "count": t["count"],
        "description": clean(t["description"]),
        "inferred": t.get("descriptionSource") == "inferred",
        "product": product,
        **({"author": t["author"]} if t.get("author") else {}),
    })

templates = []
for t in sorted(RESEARCH["fashionFactory"]["templates"], key=lambda x: x.get("priority", 99)):
    templates.append({
        "id": slug(t["name"]),
        "higgsfieldId": t.get("id"),
        "name": t["name"],
        "shots": t["previewCount"],
        "description": clean(t["description"]),
        "inferred": t.get("descriptionSource") == "inferred",
    })
if len(templates) != counts["fashionFactoryTemplates"]:
    warn("fashion template count differs from research")

defaults = {"soul-v1": next((p["id"] for p in v1 if p["name"] == "General"), None), "soul-v2": next((p["id"] for p in v2 if p["name"] == "General"), None)}


def ts(v):
    return json.dumps(v, ensure_ascii=False, indent=2)


OUT.write_text(
    "// GENERATED by scripts/gen-higgsfield-presets.py from docs/research/higgsfield-image-studios.json — do not edit.\n"
    "// Higgsfield's own preset ids (the API's style_id), names and categories; descriptions marked `inferred` are ours.\n\n"
    "export type SoulPresetModel = \"soul-v1\" | \"soul-v2\";\n\n"
    "export interface SoulPreset {\n"
    "  id: string;\n  name: string;\n  model: SoulPresetModel;\n  categories: string[];\n  description: string;\n"
    "  /** The description is Fuobe's (Higgsfield publishes none for this preset). */\n  inferred: boolean;\n"
    "  /** Soul 2.0: one of the curated moodboards in the Moodboard panel. */\n  curated?: boolean;\n}\n\n"
    "export interface PackMeta {\n  id: string;\n  higgsfieldId?: string;\n  name: string;\n  count: number;\n  description: string;\n  inferred: boolean;\n"
    "  product: \"photodump\" | \"instadump\";\n  author?: string;\n}\n\n"
    "export interface FashionTemplateMeta {\n  id: string;\n  higgsfieldId?: string;\n  name: string;\n  /** Shots in Higgsfield's preview carousel (Fuobe's photoset makes one photo per shot). */\n  shots: number;\n"
    "  description: string;\n  inferred: boolean;\n}\n\n"
    f"export const SOUL_CATEGORIES: Record<SoulPresetModel, string[]> = {ts({'soul-v1': V1_TABS, 'soul-v2': V2_TABS})};\n\n"
    f"/** The default (\"General\") preset of each model. */\nexport const SOUL_DEFAULT: Record<SoulPresetModel, string> = {ts(defaults)};\n\n"
    f"export const SOUL_PRESETS: SoulPreset[] = {ts(presets)};\n\n"
    f"export const PHOTODUMP_PACKS: PackMeta[] = {ts(packs)};\n\n"
    f"export const FASHION_TEMPLATES: FashionTemplateMeta[] = {ts(templates)};\n"
)
print(f"wrote {OUT.relative_to(ROOT)}: {len(v1)} Soul + {len(v2)} Soul 2.0 presets, {len(packs)} packs, {len(templates)} fashion templates")
