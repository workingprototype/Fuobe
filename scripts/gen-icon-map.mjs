// Regenerates src/components/preset-icons.ts from the icon names used in the catalog.
import fs from "node:fs";
const names = new Set();
for (const f of fs.readdirSync("src/lib/catalog")) {
  if (!f.endsWith(".ts")) continue;
  for (const m of fs.readFileSync(`src/lib/catalog/${f}`, "utf8").matchAll(/icon: "([A-Za-z0-9]+)"/g)) names.add(m[1]);
}
const list = [...names].sort();
const out = `// Generated by scripts/gen-icon-map.mjs — do not edit by hand.
import { ${list.join(", ")}, type LucideIcon } from "lucide-react";

export const PRESET_ICONS: Record<string, LucideIcon> = { ${list.join(", ")} };
`;
fs.writeFileSync("src/components/preset-icons.ts", out);
console.log(`wrote ${list.length} icons`);
